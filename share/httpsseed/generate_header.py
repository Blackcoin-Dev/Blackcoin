#!/usr/bin/env python3
"""Embed the exact reviewed CA snapshot; no network access or build-time refresh."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def render():
    directory = ROOT / "share/httpsseed"
    provenance = json.loads((directory / "provenance.json").read_text(encoding="utf-8"))
    data = (directory / "ca-bundle.pem").read_bytes()
    if hashlib.sha256(data).hexdigest() != provenance["ca_bundle"]["sha256"]:
        raise SystemExit("CA bundle differs from reviewed provenance pin")
    pem = data.decode("utf-8")
    if not pem.endswith("\n") or ')HTTPSSEED_CA"' in pem:
        raise SystemExit("Invalid embedding input")
    return ("// Generated by share/httpsseed/generate_header.py. Do not edit.\n"
            "// Mozilla CA bundle, MPL-2.0; see share/httpsseed/provenance.json.\n"
            "#ifndef BITCOIN_HTTPSSEED_CA_H\n#define BITCOIN_HTTPSSEED_CA_H\n\n"
            "#include <cstddef>\n\nnamespace httpsseed {\n"
            'inline constexpr char CA_BUNDLE[] = R"HTTPSSEED_CA(' + pem + ')HTTPSSEED_CA";\n'
            "inline constexpr std::size_t CA_BUNDLE_SIZE = sizeof(CA_BUNDLE) - 1;\n"
            "} // namespace httpsseed\n\n#endif // BITCOIN_HTTPSSEED_CA_H\n")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/httpsseed_ca.h"
    expected = render()
    if args.check:
        if output.read_bytes() != expected.encode("utf-8"):
            raise SystemExit("Embedded CA header is stale")
        print("Embedded CA header matches reviewed bundle")
    else:
        output.write_bytes(expected.encode("utf-8"))

if __name__ == "__main__":
    main()
